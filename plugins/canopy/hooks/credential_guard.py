#!/usr/bin/env python3
"""A tool failing on credentials ends the turn — canopy's error, never the counterpart's news.

2026-10-27, ACE turn 599fad3b on cloud-ec2-2: its first Drive call returned "Error: Method
doesn't allow unregistered callers" (as a SUCCESSFUL tool result — the MCP server put the
error in its text). The agent then emailed the outside person who had asked that "this runner
has no logins", marked her thread read, and the turn finished `done`. Nothing alarmed.
Jonathan: "this should be a clear error generated by Canopy that causes the turn to not even
get finished and creates an error and alarm to resolve."

Two modes, one file:

* **after a tool** (PostToolUse / PostToolUseFailure): if the result is a credential failure
  and this session is running a canopy turn, run `canopy turn abort` (the turn ends FAILED on
  canopy-web, which opens the failure investigation, raises its alert and starts the
  debugger's turn — canopy-web apps/harness/turn_abort.py) and stop Claude on the spot
  (`continue: false`). If canopy-web cannot be reached, the turn is still LOCKED here and
  Claude is told to stop and say so.
* **before a tool** (`--pre`, PreToolUse): once this turn is locked, every tool call is
  refused except `canopy turn abort` itself — nothing goes out and nothing is marked read, so
  the thread comes back to the agent and is answered once the credential works. This is the rail; it is keyed on the failure,
  not on what an email says (a body classifier was the first design, and dropped: ACE tells
  reviewers to log in legitimately, and wording walks around a pattern).

What counts as a credential failure is deliberately narrow (CREDENTIAL_FAILURE): the agent's
OWN login is missing, expired or refused — no credentials, an OAuth grant gone, a 401, a
bad API key, a key file that is not there. A 403 / "permission denied" is NOT one (that is
sharing on one resource, and asking for access is a fine thing to tell a person). And it
looks only where an error can be the answer, not content that merely quotes one:

* an MCP tool — the failed result, or a successful one that is SHORT (`SHORT_RESULT`) with the
  match near its start (a 48 KB transcript read that quotes an old error is not a failure);
* Bash — only a call to the agent's credentialed commands (`canopy`, `gog`, `bin/<agent>-…`):
  a failed one's error, or a short output (exit 0 through a pipe) on a line reading as an error.

The turn is the one in `~/.canopy/caller/presence/<claude_session_id>.json` (caller_context
writes it on every canopy-delivered prompt). No canopy turn — a person's own session, or the
owner typing at the keyboard — and this does nothing. Any error → exit 0 silently.
"""
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import time

CALLER_ROOT = os.path.expanduser("~/.canopy/caller")
LOCK_ROOT = os.path.expanduser("~/.canopy/turn-abort")  # orchestrator/turn_cli.py LOCK_DIR
LOCK_MAX_AGE = 24 * 3600
_SID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,199}$")
_TURN = re.compile(r"^[0-9a-fA-F-]{8,64}$")

SHORT_RESULT = 2000
NEAR_START = 400
ABORT_TIMEOUT = 30

CREDENTIAL_FAILURE = [re.compile(p, re.IGNORECASE) for p in (
    r"unregistered callers",                                   # Google: no credentials at all
    r"\binvalid_grant\b",                                      # OAuth refresh token dead
    r"token has been expired or revoked",
    r"invalid authentication credentials",
    r"could not load the default credentials",
    r"\binvalid_client\b",
    r"\b401\b[^\n]{0,40}unauthori[sz]ed|unauthori[sz]ed[^\n]{0,40}\b401\b",
    r"\b(?:http|status|status code|error)[ :]*401\b",
    r"\binvalid api[ _-]?key\b|\bapi key not valid\b|\bincorrect api key\b",
    r"\b(?:missing|no) (?:api key|credentials|access token)\b",
    r"\bauthentication (?:required|failed)\b|\bnot authenticated\b",
    r"\b(?:ENOENT|no such file)[^\n]{0,160}(?:key|credential|token)[\w.-]*\.json",
)] + [re.compile(r"\bUNAUTHENTICATED\b")]                     # gRPC status, upper case only

#: A failed Bash call is judged only when it ran one of these (the agent's own logins).
CREDENTIALED_COMMAND = re.compile(r"^\s*(?:\S+/)?(?:canopy|gog|bin/[\w.-]+)\b")
_SEGMENTS = re.compile(r"&&|\|\||[;|\n]")
_CD = re.compile(r"^\s*cd(?:\s|$)")
_ERROR_LINE = re.compile(r"error|fail|refus|denied|exception|traceback", re.IGNORECASE)
_ABORT_COMMAND = re.compile(r"^\s*(?:\S+/)?canopy\s+turn\s+abort\b")
#: Tools whose whole job is to report "you need to sign in".
_AUTH_TOOL = re.compile(r"__(?:complete_)?authenticat", re.IGNORECASE)

PRE_REASON = (
    "canopy credential_guard: this turn was aborted — {reason} It cannot do its work, so it "
    "takes no more actions: nothing is sent and nothing is marked read, so the thread comes "
    "back to the agent and is answered once the credential works. {filed} End your reply now with one line saying the turn "
    "was aborted and why. Do not tell any counterpart about logins or runner setup."
)


def _text(value) -> str:
    """Every text in a tool result, however it is shaped."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, dict):
        if isinstance(value.get("text"), str):
            return value["text"]
        parts = [_text(value[k]) for k in ("content", "error", "stderr", "stdout", "output",
                                           "result") if k in value]
        return "\n".join(p for p in parts if p) or json.dumps(value)[:SHORT_RESULT * 2]
    if isinstance(value, list):
        return "\n".join(t for t in (_text(v) for v in value) if t)
    return str(value)


def _segments(command: str) -> list[str]:
    """The simple commands in a shell line, quote-aware (a `;` inside --reason is not one)."""
    try:
        lex = shlex.shlex(command or "", posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        segs, cur = [], []
        for tok in lex:
            if tok and set(tok) <= set("&|;"):
                segs.append(" ".join(cur))
                cur = []
            else:
                cur.append(tok)
        segs.append(" ".join(cur))
    except ValueError:  # unbalanced quotes: fall back to a plain split
        segs = _SEGMENTS.split(command or "")
    return [seg for seg in segs if seg.strip()]


def runs_credentialed(command: str) -> bool:
    return any(CREDENTIALED_COMMAND.match(seg) for seg in _segments(command))


def is_abort(command: str) -> bool:
    """`canopy turn abort …`, optionally after a `cd` — and nothing else."""
    segs = _segments(command)
    return (any(_ABORT_COMMAND.match(seg) for seg in segs)
            and all(_ABORT_COMMAND.match(seg) or _CD.match(seg) for seg in segs))


def match(text: str):
    for pattern in CREDENTIAL_FAILURE:
        m = pattern.search(text)
        if m:
            return m
    return None


def credential_failure(data: dict) -> str:
    """The error text when this tool call failed on the agent's credentials, else ""."""
    tool = str(data.get("tool_name") or "")
    failed = data.get("hook_event_name") == "PostToolUseFailure" or "error" in data
    text = _text(data.get("error") if "error" in data else data.get("tool_response")).strip()
    if not text:
        return ""
    if tool.startswith("mcp__"):
        if _AUTH_TOOL.search(tool):
            return ""
        if failed:
            m = match(text[:SHORT_RESULT * 4])
        else:
            if len(text) > SHORT_RESULT:
                return ""
            m = match(text)
            if m and m.start() > NEAR_START:
                m = None
        return text if m else ""
    if tool == "Bash":
        command = str((data.get("tool_input") or {}).get("command") or "")
        if not runs_credentialed(command) or is_abort(command):
            return ""
        tail = text[-SHORT_RESULT:]
        if failed:
            return tail if match(tail) else ""
        # Exit 0 can still be a failure (`canopy email send … 2>&1 | tail -2`): judged only
        # when short, and only on a line that itself reads as an error.
        if len(text) > SHORT_RESULT:
            return ""
        return tail if any(match(line) and _ERROR_LINE.search(line)
                           for line in tail.splitlines()) else ""
    return ""


def current_turn(session_id: str, *, root=None) -> str:
    if not session_id or not _SID.match(session_id):
        return ""
    try:
        with open(os.path.join(root or CALLER_ROOT, "presence", f"{session_id}.json"),
                  encoding="utf-8") as fh:
            rec = json.load(fh)
    except (OSError, ValueError):
        return ""
    tid = str(rec.get("turn_id") or "") if isinstance(rec, dict) else ""
    return tid if _TURN.match(tid) else ""


def read_lock(turn_id: str, *, root=None, now=time.time):
    try:
        with open(os.path.join(root or LOCK_ROOT, f"{turn_id}.json"), encoding="utf-8") as fh:
            rec = json.load(fh)
    except (OSError, ValueError):
        return None
    if not isinstance(rec, dict) or now() - float(rec.get("at") or 0) > LOCK_MAX_AGE:
        return None
    return rec


def summary(tool: str, error: str) -> str:
    first = " ".join(error.split())[:300]
    return f"{tool} failed on the agent's credentials: {first}"


def run_abort(turn_id: str, tool: str, reason: str) -> bool:
    """`canopy turn abort` — it files the abort AND writes the lock. True when filed."""
    exe = shutil.which("canopy")
    if not exe:
        return False
    try:
        done = subprocess.run([exe, "turn", "abort", "--turn", turn_id, "--tool", tool,
                               "--reason", reason], stdin=subprocess.DEVNULL,
                              capture_output=True, timeout=ABORT_TIMEOUT)
    except (OSError, subprocess.SubprocessError):
        return False
    return done.returncode == 0


def write_lock(turn_id: str, tool: str, reason: str, *, root=None) -> None:
    """The lock without the CLI (none on PATH, or it timed out): the turn still stops."""
    d = root or LOCK_ROOT
    path = os.path.join(d, f"{turn_id}.json")
    if os.path.exists(path):
        return
    try:
        os.makedirs(d, mode=0o700, exist_ok=True)
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump({"turn_id": turn_id, "reason": reason, "tool": tool, "filed": False,
                       "at": time.time()}, fh)
    except OSError:
        pass


def after_tool(data: dict) -> dict | None:
    error = credential_failure(data)
    if not error:
        return None
    turn_id = current_turn(str(data.get("session_id") or ""))
    if not turn_id or read_lock(turn_id):
        return None
    tool = str(data.get("tool_name") or "")
    reason = summary(tool, error)
    filed = run_abort(turn_id, tool, reason)
    write_lock(turn_id, tool, reason)
    if filed:
        return {"continue": False,
                "stopReason": f"Canopy aborted this turn: {reason} The turn is marked failed "
                              "and raised with the agent's owner; it takes no further actions."}
    return {"decision": "block",
            "reason": PRE_REASON.format(
                reason=reason,
                filed=("canopy-web could not be told, so run `canopy turn abort --turn "
                       f"{turn_id} --tool {tool} --reason \"<that error>\"` once; if it fails "
                       "again, end on: \"turn aborted, NOT filed on canopy-web\".")) }


def before_tool(data: dict) -> dict | None:
    turn_id = current_turn(str(data.get("session_id") or ""))
    lock = read_lock(turn_id) if turn_id else None
    if not lock:
        return None
    if data.get("tool_name") == "Bash" and is_abort(
            str((data.get("tool_input") or {}).get("command") or "")):
        return None
    filed = ("Canopy has marked it failed and raised it with the owner." if lock.get("filed")
             else f"It is NOT yet filed on canopy-web: run `canopy turn abort --turn {turn_id} "
                  "--reason \"…\"` (the one call allowed).")
    return {"hookSpecificOutput": {
        "hookEventName": "PreToolUse", "permissionDecision": "deny",
        "permissionDecisionReason": PRE_REASON.format(reason=lock.get("reason") or "", filed=filed)}}


def main(argv) -> int:
    try:
        data = json.load(sys.stdin)
        out = before_tool(data) if "--pre" in argv else after_tool(data)
        if out:
            print(json.dumps(out))
    except Exception:  # noqa: BLE001 — never wedge a session on a broken guard
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
