"""Canopy Vault zero-knowledge v1 (canopy-web#1550): the client library reproduces the
NORMATIVE vectors byte for byte.

`fixtures/vault_zk/zk_v1_vectors.json` is a verbatim copy of canopy-web's
`docs/vault/zk-v1/zk_v1_vectors.json` (generated by `zk_v1_reference.py`). Every output is
recomputed from the vector's inputs, with the fixed ephemeral keys, nonces and salts
injected through the test-only keyword arguments — and compared as exact strings/dicts.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest
from cryptography.hazmat.primitives.asymmetric import ec

from orchestrator import vault_zk as zk

VECTORS = json.loads((Path(__file__).parent / "fixtures" / "vault_zk" /
                      "zk_v1_vectors.json").read_text(encoding="utf-8"))
I, O = VECTORS["inputs"], VECTORS["outputs"]


def _priv(scalar_hex: str) -> ec.EllipticCurvePrivateKey:
    return ec.derive_private_key(int(scalar_hex, 16), ec.SECP256R1())


VK = bytes.fromhex(I["vk_hex"])
NONCE = bytes.fromhex(I["nonce_hex"])
SALT = bytes.fromhex(I["salt_hex"])
DEVICE = _priv(I["device_priv_scalar_hex"])
USER = _priv(I["user_priv_scalar_hex"])
AGENT, KV, USER_ID = I["agent_id"], I["kv"], I["user_id"]


def test_the_vectors_are_the_v1_format():
    assert VECTORS["format"] == zk.FORMAT == "canopy-vault/zk/v1"


def test_public_jwks_and_device_jkt():
    assert zk.jwk(DEVICE.public_key()) == I["device_pub_jwk"]
    assert zk.jwk(USER.public_key()) == I["user_pub_jwk"]
    assert zk.jkt(DEVICE.public_key()) == I["device_jkt"]
    assert zk.jwk_thumbprint(I["device_pub_jwk"]) == I["device_jkt"]


def test_value_is_byte_exact():
    got = zk.encrypt_value(VK, AGENT, I["value_name"], KV, I["value_plaintext"], nonce=NONCE)
    assert got == O["value"]
    assert zk.decrypt_value(VK, AGENT, I["value_name"], KV, O["value"]) == I["value_plaintext"]


def test_device_wrap_is_byte_exact():
    info = zk.device_info(AGENT, KV, I["device_jkt"])
    got = zk.wrap_ecdh_es(VK, I["device_pub_jwk"], info,
                          ephemeral=_priv(I["ephemeral_device_wrap_scalar_hex"]), nonce=NONCE)
    assert got == O["device_wrap"]
    assert zk.unwrap_ecdh_es(O["device_wrap"], DEVICE, info) == VK


def test_device_shared_secret_and_unwrap_with_z():
    """The hardware path: the key hands back Z, the library does the rest."""
    epk = zk.public_key_from_point(zk.wrap_epk_point(O["device_wrap"]))
    z = DEVICE.exchange(ec.ECDH(), epk)
    assert z.hex() == O["device_wrap_shared_secret_hex"]
    info = zk.device_info(AGENT, KV, I["device_jkt"])
    assert zk.unwrap_ecdh_es_with_z(O["device_wrap"], z, zk.point_from_jwk(I["device_pub_jwk"]),
                                    info) == VK


def test_member_wrap_is_byte_exact():
    info = zk.member_info(AGENT, KV, USER_ID)
    got = zk.wrap_ecdh_es(VK, USER.public_key(), info,
                          ephemeral=_priv(I["ephemeral_member_wrap_scalar_hex"]), nonce=NONCE)
    assert got == O["member_wrap"]
    assert zk.unwrap_ecdh_es(O["member_wrap"], USER, info) == VK


def test_prf_input_and_user_key_seal_are_byte_exact():
    assert zk.b64u(zk.prf_input(USER_ID)) == O["prf_input_b64u"]
    scalar = bytes.fromhex(I["user_priv_scalar_hex"])
    prf_out = bytes.fromhex(I["prf_output_hex"])
    got = zk.seal_user_key(scalar, USER_ID, I["credential_id_b64u"], prf_out, salt=SALT,
                           nonce=NONCE)
    assert got == O["user_key_seal"]
    opened = zk.open_user_key(O["user_key_seal"], USER_ID, prf_out)
    assert opened == scalar
    # the person path end to end: open the seal, then unwrap the member wrap with it
    assert zk.unwrap_ecdh_es(O["member_wrap"], _priv(opened.hex()),
                             zk.member_info(AGENT, KV, USER_ID)) == VK


def test_recovery_wrap_and_code_are_byte_exact():
    r = bytes.fromhex(I["recovery_secret_hex"])
    assert r == hashlib.sha256(b"test-recovery-secret").digest()
    assert zk.wrap_recovery(VK, AGENT, KV, r, salt=SALT, nonce=NONCE) == O["recovery_wrap"]
    assert zk.recovery_code(r) == O["recovery_code"]
    assert zk.parse_recovery_code(O["recovery_code"]) == r
    assert zk.unwrap_recovery(O["recovery_wrap"], AGENT, KV,
                              zk.parse_recovery_code(O["recovery_code"])) == VK


def test_recovery_code_is_forgiving_of_case_spacing_and_lookalikes():
    code = O["recovery_code"]
    sloppy = code.lower().replace("-", " ").replace("0", "o").replace("1", "l")
    assert zk.parse_recovery_code(sloppy) == bytes.fromhex(I["recovery_secret_hex"])
    with pytest.raises(zk.ZkError):
        zk.parse_recovery_code(code[:-5])
    with pytest.raises(zk.ZkError):
        zk.parse_recovery_code(code.replace("V", "U", 1))


@pytest.mark.parametrize("bad", [
    lambda: zk.decrypt_value(VK, "43", I["value_name"], KV, O["value"]),
    lambda: zk.decrypt_value(VK, AGENT, "other-name", KV, O["value"]),
    lambda: zk.decrypt_value(VK, AGENT, I["value_name"], 2, O["value"]),
    lambda: zk.decrypt_value(bytes(32), AGENT, I["value_name"], KV, O["value"]),
    lambda: zk.unwrap_ecdh_es(O["device_wrap"], DEVICE, zk.device_info(AGENT, 2, I["device_jkt"])),
    lambda: zk.unwrap_ecdh_es(O["device_wrap"], USER, zk.device_info(AGENT, KV, I["device_jkt"])),
    lambda: zk.unwrap_ecdh_es(O["member_wrap"], USER, zk.member_info(AGENT, KV, "8")),
    lambda: zk.open_user_key(O["user_key_seal"], "8", bytes.fromhex(I["prf_output_hex"])),
    lambda: zk.unwrap_recovery(O["recovery_wrap"], "43", KV, bytes.fromhex(I["recovery_secret_hex"])),
])
def test_every_binding_is_enforced(bad):
    with pytest.raises(zk.ZkError):
        bad()


def test_fresh_randomness_round_trips_and_differs():
    vk = zk.random_vk()
    a = zk.encrypt_value(vk, "1", "n", 3, "v")
    b = zk.encrypt_value(vk, "1", "n", 3, "v")
    assert a != b and zk.decrypt_value(vk, "1", "n", 3, a) == "v"
    w = zk.wrap_ecdh_es(vk, I["device_pub_jwk"], "info")
    assert zk.unwrap_ecdh_es(w, DEVICE, "info") == vk
    r = zk.random_recovery_secret()
    assert zk.parse_recovery_code(zk.recovery_code(r)) == r


def test_bad_keys_and_shapes_are_refused():
    with pytest.raises(zk.ZkError):
        zk.public_key_from_jwk({"kty": "EC", "crv": "P-384", "x": "", "y": ""})
    off_curve = dict(I["device_pub_jwk"], y=I["user_pub_jwk"]["y"])
    with pytest.raises(zk.ZkError):
        zk.wrap_ecdh_es(VK, off_curve, "info")
    with pytest.raises(zk.ZkError):
        zk.wrap_epk_point({"alg": "recovery"})
    with pytest.raises(zk.ZkError):
        zk.decrypt_value(VK, AGENT, "n", KV, "plain")
    with pytest.raises(zk.ZkError):
        zk.encrypt_value(b"short", AGENT, "n", KV, "v")


# ── 4b. passphrase + Secret Key (2SKD) seal ───────────────────────────────────

def test_2skd_seal_and_secret_key_code_are_byte_exact():
    scalar = bytes.fromhex(I["user_priv_scalar_hex"])
    sk = bytes.fromhex(I["secret_key_hex"])
    got = zk.seal_user_key_2skd(scalar, USER_ID, I["passphrase"], sk, salt=SALT, nonce=NONCE)
    assert got == O["user_key_seal_2skd"]
    assert zk.secret_key_code(sk) == O["secret_key_code"]
    assert zk.parse_secret_key_code(O["secret_key_code"]) == sk
    assert zk.parse_secret_key_code(O["secret_key_code"].lower().replace("-", " ")) == sk
    opened = zk.open_user_key_2skd(O["user_key_seal_2skd"], USER_ID, I["passphrase"], sk)
    assert opened == scalar
    # NFKC: the ligature "ﬁ" and plain "fi" are the same passphrase
    assert zk.open_user_key_2skd(O["user_key_seal_2skd"], USER_ID,
                                 "correct horse battery staple fi", sk) == scalar
    assert zk.unwrap_ecdh_es(O["member_wrap"], _priv(opened.hex()),
                             zk.member_info(AGENT, KV, USER_ID)) == VK


@pytest.mark.parametrize("bad", [
    lambda sk: zk.open_user_key_2skd(O["user_key_seal_2skd"], USER_ID, "wrong passphrase", sk),
    lambda sk: zk.open_user_key_2skd(O["user_key_seal_2skd"], USER_ID, I["passphrase"], bytes(16)),
    lambda sk: zk.open_user_key_2skd(O["user_key_seal_2skd"], "8", I["passphrase"], sk),
    lambda sk: zk.open_user_key_2skd(dict(O["user_key_seal_2skd"], i=1000), USER_ID,
                                     I["passphrase"], sk),
    lambda sk: zk.parse_secret_key_code("CV1-" + "U" * 26),
    lambda sk: zk.parse_secret_key_code(O["secret_key_code"][:-2]),
])
def test_2skd_bindings_are_enforced(bad):
    with pytest.raises(zk.ZkError):
        bad(bytes.fromhex(I["secret_key_hex"]))


def test_the_committed_reference_regenerates_the_committed_vectors():
    """Both fixture files are verbatim copies of canopy-web's normative pair; this pins
    that they belong together."""
    import importlib.util
    path = Path(__file__).parent / "fixtures" / "vault_zk" / "zk_v1_reference.py"
    spec = importlib.util.spec_from_file_location("zk_v1_reference", path)
    ref = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ref)
    assert ref.vectors() == VECTORS
